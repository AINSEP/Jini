/**
 * The `media` provider contract: what a plugin hands a host so one media vendor (its catalogue row,
 * its models and the adapters serving its routes) can be registered without the host's neutral code
 * naming that vendor.
 *
 * Why structural, not imported: a plugin cannot import the host's dispatch package, so every shape a
 * contribution touches is restated here at the smallest size the adapters need. The host's own richer
 * request/context types are assignable to these (a function taking fewer fields accepts more).
 *
 * Wire helpers arrive as {@link MediaWirePort} through provider initialization, so a vendor's adapter
 * reuses the host's request builder, response parsing and safe download instead of copying them.
 */
import type { MediaModel, MediaProvider } from './media-providers-catalog.js';

/** The `contract` name a media plugin registers under. */
export const MEDIA_PROVIDER_CONTRACT_ID = 'media';

/** The slice of one generation request an adapter reads. */
export interface MediaRenderContext {
  readonly wireModel: string;
  readonly prompt: string;
  readonly aspect: string | undefined;
  readonly voice: string;
  readonly language: string;
  readonly requestInit: Pick<RequestInit, 'dispatcher'>;
}

/** Credentials a host resolved for one provider; never read from the environment by an adapter. */
export interface MediaProviderCredentials {
  readonly apiKey?: string;
  readonly baseUrl?: string;
}

/** One vendor HTTP request plus values `parseResponse` needs again. */
export interface MediaVendorRequest<Meta = undefined> {
  readonly url: string;
  readonly init: RequestInit;
  readonly meta: Meta;
}

/** Generated bytes with a provenance note. */
export interface MediaRenderResult {
  readonly bytes: Buffer;
  readonly providerNote: string;
  readonly suggestedExt?: string;
}

/** Throws a plain-words error when the credentials cannot make a request. */
export type MediaCredentialGuard = (required: { credentials: MediaProviderCredentials }) => void;

/** One route's request/response pair: validate credentials, build one request, parse its response. */
export interface MediaVendorAdapter<Meta = never> {
  readonly requireCredential?: MediaCredentialGuard;
  buildRequest(required: { ctx: MediaRenderContext; credentials: MediaProviderCredentials }): MediaVendorRequest<Meta>;
  parseResponse(required: { resp: Response; ctx: MediaRenderContext; request: MediaVendorRequest<Meta> }): Promise<MediaRenderResult>;
}

/** The options a raw-bytes response parser needs; `Meta` is whatever `buildRequest` returned. */
export interface MediaRawBytesParserOptions<Meta> {
  readonly errorTag: string;
  readonly zeroBytesMessage: string;
  readonly note: (required: { bytes: Buffer; meta: Meta }) => string;
  readonly suggestedExt: string;
}

/** Generic wire helpers a host lends a media plugin; none of them knows any vendor. */
export interface MediaWirePort {
  requireApiKey(required: { message: string }): MediaCredentialGuard;
  /** The OpenAI-images-compatible aspect names; an unknown aspect falls back to the wide default. */
  imageAspectFor(required: { aspect: string | undefined }): string;
  /** `<baseUrl>/images/generations` for an OpenAI-images-compatible endpoint. */
  imageGenerationUrl(required: { baseUrl: string }): string;
  jsonPostInit(required: { ctx: Pick<MediaRenderContext, 'requestInit'>; body: unknown }, optional?: { apiKey?: string }): RequestInit;
  parseJson(required: { resp: Response; providerTag: string }): Promise<unknown>;
  /** Bytes of the first `{ data: [{ b64_json | url }] }` entry; a URL is fetched through the host's guarded client. */
  imageBytesFromData(required: { data: unknown; providerTag: string; ctx: MediaRenderContext }): Promise<Buffer>;
  sniffImageExt(required: { bytes: Buffer }): string;
  createRawBytesParser<Meta>(required: MediaRawBytesParserOptions<Meta>): MediaVendorAdapter<Meta>['parseResponse'];
}

/** A catalogued model plus the surface (and audio kind) it is offered on. */
export interface MediaContributionModel extends MediaModel {
  readonly surface: 'image' | 'video' | 'audio';
  readonly audioKind?: 'music' | 'speech' | 'sfx';
  readonly order?: number;
}

/** Everything one vendor brings, registered as one unit. */
export interface MediaProviderContribution {
  readonly provider: MediaProvider;
  readonly models: readonly MediaContributionModel[];
  /** Route key (`image`, `video`, `audio:speech`, ...) to the adapter serving it. */
  readonly adapters: Readonly<Record<string, MediaVendorAdapter<never>>>;
}
