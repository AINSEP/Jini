import Database from "better-sqlite3";
import { PGlite } from "@electric-sql/pglite";
import { sql } from "kysely";
import { sqliteKernel } from "../../../kernel/sqlite/index.js";
import { openPgliteKernel } from "../../../kernel/pglite/index.js";
import type { KyselyKernel } from "../../../kernel/port.js";
import type { SettingsTables } from "../../repo.sql.js";

/**
 * @file DDL for the five settings tables, copied from the host schema's migrations (same columns, keys and
 * unique indexes) without the workspace foreign keys: the adapter owns no schema, so a fixture needs none.
 * `seq` of the ledger is an integer on both dialects so it reads back as a number.
 */

export const TABLES: SettingsTables = {
  definitions: "setting_definitions",
  valuesGlobal: "setting_values_global",
  valuesWorkspace: "setting_values_workspace",
  valuesUser: "setting_values_user",
  revisions: "setting_revisions",
};

const VALUE_COLUMNS = "value_json text, state text DEFAULT 'set' NOT NULL, def_version integer NOT NULL, seq integer NOT NULL, updated_by text NOT NULL, updated_at text NOT NULL, origin_plugin_id text";
const DEFINITION_COLUMNS = "setting_id text NOT NULL, version integer DEFAULT 1 NOT NULL, workspace_id text, namespace text NOT NULL, key text NOT NULL, owner_kind text NOT NULL, owner_id text, schema_json text NOT NULL, default_json text, scopes integer NOT NULL, secret integer DEFAULT 0 NOT NULL, status text NOT NULL, alias_of_key text, alias_of_ns text, coercion_json text, created_at text NOT NULL, updated_at text NOT NULL";
const REVISION_COLUMNS = "entity_kind text NOT NULL, setting_id text NOT NULL, scope text, workspace_id text, principal_id text, op text NOT NULL, before_json text, after_json text, def_version integer NOT NULL, actor text NOT NULL, origin_plugin_id text, change_set_id text, created_at text NOT NULL";

const common = [
  `CREATE TABLE setting_definitions (${DEFINITION_COLUMNS})`,
  "CREATE UNIQUE INDEX pk_setting_definitions ON setting_definitions (setting_id, version)",
  `CREATE TABLE setting_values_global (setting_id text PRIMARY KEY NOT NULL, ${VALUE_COLUMNS})`,
  `CREATE TABLE setting_values_workspace (setting_id text NOT NULL, workspace_id text NOT NULL, ${VALUE_COLUMNS})`,
  "CREATE UNIQUE INDEX pk_setting_values_workspace ON setting_values_workspace (workspace_id, setting_id)",
  `CREATE TABLE setting_values_user (setting_id text NOT NULL, workspace_id text NOT NULL, principal_id text NOT NULL, ${VALUE_COLUMNS})`,
  "CREATE UNIQUE INDEX pk_setting_values_user ON setting_values_user (workspace_id, principal_id, setting_id)",
];
const sqliteStatements = [...common, `CREATE TABLE setting_revisions (seq integer PRIMARY KEY AUTOINCREMENT NOT NULL, ${REVISION_COLUMNS})`];
const postgresStatements = [...common, `CREATE TABLE setting_revisions (seq integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ${REVISION_COLUMNS})`];

export interface OpenKernel {
  kernel: KyselyKernel<unknown>;
  dialect: "sqlite" | "postgres";
  close: () => Promise<void>;
}

/** A fresh in-memory database of the dialect with the five tables applied. */
export async function openSettingsKernel({ dialect }: { dialect: "sqlite" | "postgres" }, _optional: Record<string, never> = {}): Promise<OpenKernel> {
  const opened: KyselyKernel<unknown> = dialect === "sqlite" ? sqliteKernel<unknown>(new Database(":memory:")) : openPgliteKernel({ PGlite });
  for (const statement of dialect === "sqlite" ? sqliteStatements : postgresStatements) await opened.execute(sql.raw(statement));
  return { kernel: opened, dialect, close: () => opened.close() };
}
