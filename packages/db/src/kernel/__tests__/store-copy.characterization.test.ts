import { PGlite } from "@electric-sql/pglite";
import { sql } from "kysely";
import { afterEach, expect, test } from "vitest";
import { openPgliteKernel } from "../pglite/index.js";
import type { StorageKernel } from "../port.js";
import { copyPgStore, type StoreCopyScope } from "../store-copy.js";

const scope: StoreCopyScope = { schemas: ["public"], ledgers: [] };
const opened: StorageKernel<unknown>[] = [];
afterEach(async () => { for (const kernel of opened.splice(0)) await kernel.close(); });
function open(_required: {}, _optional = {}): StorageKernel<unknown> {
  const kernel = openPgliteKernel({ PGlite });
  opened.push(kernel);
  return kernel;
}

test("created tables retain non-FK constraints, indexes and generated columns; existing and created FKs are restored before the hook", async () => {
  const source = open({});
  const target = open({});
  for (const kernel of [source, target]) {
    await kernel.execute(sql`CREATE TABLE parent (id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY)`);
    await kernel.execute(sql`CREATE TABLE existing_child (id INTEGER PRIMARY KEY, parent_id INTEGER REFERENCES parent(id))`);
  }
  await source.execute(sql`INSERT INTO parent OVERRIDING SYSTEM VALUE VALUES (7)`);
  await source.execute(sql`INSERT INTO existing_child VALUES (1, 7)`);
  await source.execute(sql`CREATE TABLE extra (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id INTEGER REFERENCES parent(id), value INTEGER NOT NULL CHECK (value > 0), doubled INTEGER GENERATED ALWAYS AS (value * 2) STORED, UNIQUE (value))`);
  await source.execute(sql`CREATE INDEX extra_parent ON extra(parent_id)`);
  await source.execute(sql`INSERT INTO extra (id, parent_id, value) VALUES (11, 7, 3)`);
  await source.execute(sql`CREATE TABLE empty_identity (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`);
  let hooked = false;
  const report = await copyPgStore({ source, target, scope }, { onCopied: async () => {
    expect(target.inTransaction()).toBe(true);
    expect(await target.query(sql`SELECT id, parent_id, value, doubled FROM extra`)).toEqual([{ id: 11, parent_id: 7, value: 3, doubled: 6 }]);
    expect(await target.query(sql`SELECT count(*)::int AS n FROM pg_constraint WHERE conrelid IN ('extra'::regclass, 'existing_child'::regclass) AND contype = 'f'`)).toEqual([{ n: 2 }]);
    hooked = true;
  } });
  expect(hooked).toBe(true);
  expect(report).toEqual([
    { table: "public.empty_identity", rows: 0, created: true },
    { table: "public.existing_child", rows: 1, created: false },
    { table: "public.extra", rows: 1, created: true },
    { table: "public.parent", rows: 1, created: false },
  ]);
  expect(await target.query(sql`INSERT INTO empty_identity DEFAULT VALUES RETURNING id`)).toEqual([{ id: 1 }]);
  expect(await target.query(sql`INSERT INTO parent DEFAULT VALUES RETURNING id`)).toEqual([{ id: 8 }]);
  expect(await target.query(sql`INSERT INTO extra (parent_id, value) VALUES (7, 4) RETURNING id, doubled`)).toEqual([{ id: 12, doubled: 8 }]);
  expect(await target.query(sql`SELECT indexname FROM pg_indexes WHERE tablename = 'extra' ORDER BY indexname`)).toEqual([
    { indexname: "extra_parent" }, { indexname: "extra_pkey" }, { indexname: "extra_value_key" },
  ]);
  await expect(target.execute(sql`INSERT INTO existing_child VALUES (2, 999)`)).rejects.toThrow();
  await expect(target.execute(sql`INSERT INTO extra (parent_id, value) VALUES (999, 9)`)).rejects.toThrow();
  await expect(target.execute(sql`INSERT INTO extra (value) VALUES (0)`)).rejects.toThrow();
  await expect(target.execute(sql`INSERT INTO extra (value) VALUES (3)`)).rejects.toThrow();
});

test("an empty source and target return an empty report without a hook", async () => {
  expect(await copyPgStore({ source: open({}), target: open({}), scope })).toEqual([]);
});

test("an occupied target refuses under the transaction and rolls back the dropped FK", async () => {
  const source = open({});
  const target = open({});
  for (const kernel of [source, target]) {
    await kernel.execute(sql`CREATE TABLE parent (id INTEGER PRIMARY KEY)`);
    await kernel.execute(sql`CREATE TABLE child (id INTEGER REFERENCES parent(id))`);
  }
  await target.execute(sql`INSERT INTO parent VALUES (1)`);
  await expect(copyPgStore({ source, target, scope })).rejects.toThrow("the target database already holds data (public.parent); nothing was copied");
  await expect(target.execute(sql`INSERT INTO child VALUES (999)`)).rejects.toThrow();
  expect(await target.query(sql`SELECT id FROM parent`)).toEqual([{ id: 1 }]);
});

test("a late hook failure rolls back created tables and existing rows", async () => {
  const source = open({});
  const target = open({});
  for (const kernel of [source, target]) await kernel.execute(sql`CREATE TABLE existing (id TEXT PRIMARY KEY)`);
  await source.execute(sql`INSERT INTO existing VALUES ('original')`);
  await source.execute(sql`CREATE TABLE extra (id TEXT PRIMARY KEY)`);
  await expect(copyPgStore({ source, target, scope }, { onCopied: async () => { throw new Error("late failure"); } })).rejects.toThrow("late failure");
  expect(await target.query(sql`SELECT id FROM existing`)).toEqual([]);
  expect(await target.query(sql`SELECT to_regclass('public.extra') AS extra`)).toEqual([{ extra: null }]);
});

test("a source with only generated columns cannot transfer its rows (reported, not fixed)", async () => {
  const source = open({});
  const target = open({});
  await source.execute(sql`CREATE TABLE generated_only (value INTEGER GENERATED ALWAYS AS (1) STORED)`);
  await source.execute(sql`INSERT INTO generated_only DEFAULT VALUES`);
  await expect(copyPgStore({ source, target, scope })).rejects.toThrow("table public.generated_only did not verify after the copy");
  expect(await target.query(sql`SELECT to_regclass('public.generated_only') AS extra`)).toEqual([{ extra: null }]);
  expect(await source.query(sql`SELECT value FROM generated_only`)).toEqual([{ value: 1 }]);
});
