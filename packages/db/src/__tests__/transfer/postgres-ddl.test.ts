/** The public named-argument DDL API: quoting, identifier fitting, table/index SQL and tag validation. */
import { createHash } from "node:crypto";
import { expect, it } from "vitest";
import { constraintSql, createTableSql, fitIdentifier, indexSql, qualified, quoteIdent, quoteLiteral, reseedIdentitySql, type TransferTable } from "../../transfer/index.js";

const table: TransferTable = {
  name: "notes",
  columns: [
    { name: "id", sqlType: "bigint", notNull: true, identity: "BY DEFAULT" },
    { name: "title", sqlType: "text", notNull: false, default: "'untitled'" },
  ],
  primaryKey: ["id"],
  indexes: [{ name: "notes_title", columns: ["title"], unique: true }, { name: "notes_lower", columns: [], expressions: ["lower(title)"], unique: false, where: "title IS NOT NULL" }],
  foreignKeys: [],
  checks: [],
};

it("quotes identifiers and literals by doubling their own quote character", () => {
  expect(quoteIdent({ name: 'odd"name' })).toBe('"odd""name"');
  expect(quoteLiteral({ value: "it's" })).toBe("'it''s'");
  expect(qualified({ schema: "app", table: 'a"b' })).toBe('"app"."a""b"');
});

it("keeps an identifier that fits in 63 bytes and cuts a longer one to a hashed 63-byte name", () => {
  expect(fitIdentifier({ name: "short_name" })).toBe("short_name");
  const long = "x".repeat(70);
  const fitted = fitIdentifier({ name: long });
  expect(fitted).toBe(`${"x".repeat(54)}_${createHash("sha256").update(long).digest("hex").slice(0, 8)}`);
  expect(Buffer.byteLength(fitted)).toBe(63);
});

it("renders a table with identity, default, NOT NULL and primary key, and its plain and expression indexes", () => {
  expect(createTableSql({ schema: "app", table })).toBe(
    'CREATE TABLE "app"."notes" ("id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, "title" text DEFAULT \'untitled\', PRIMARY KEY ("id"));\n',
  );
  expect(indexSql({ schema: "app", table })).toBe(
    'CREATE UNIQUE INDEX "notes_title" ON "app"."notes" ("title");\n' +
    'CREATE INDEX "notes_lower" ON "app"."notes" (lower(title)) WHERE title IS NOT NULL;\n',
  );
});

it("uses the default dollar-quote tag unless a valid one is given, and refuses an invalid tag", () => {
  expect(reseedIdentitySql({ schema: "app", table })).toContain("$transfer$");
  expect(reseedIdentitySql({ schema: "app", table }, { sqlTag: "copy_2" })).toContain("$copy_2$");
  const checked = { ...table, checks: [{ name: "notes_title_len", sql: "length(title) < 200" }] };
  const constraints = constraintSql({ schema: "app", tables: [checked], unvalidatedTable: "pg_temp.unchecked" }, { sqlTag: "copy_2" });
  expect(constraints).toContain('ALTER TABLE "app"."notes" ADD CONSTRAINT "notes_title_len" CHECK (length(title) < 200) NOT VALID;');
  expect(constraints).toContain("$copy_2$");
  expect(constraints).not.toContain("$transfer$");
  for (const sqlTag of ["Upper", "1digit", "has-dash", "x$y", ""]) {
    expect(() => reseedIdentitySql({ schema: "app", table }, { sqlTag })).toThrow("invalid SQL dollar-quote tag");
    expect(() => constraintSql({ schema: "app", tables: [table], unvalidatedTable: "pg_temp.unchecked" }, { sqlTag })).toThrow("invalid SQL dollar-quote tag");
  }
});
