import { PGlite } from "@electric-sql/pglite";
import { sql } from "kysely";
import { afterEach, expect, it } from "vitest";

import { openPgliteKernel } from "../kernel/pglite/index.js";
import type { StorageKernel } from "../kernel/port.js";
import { copyPgStore, readCatalog, StoreCopyError, type StoreCopyScope } from "../kernel/store-copy.js";

/**
 * @file A table the target lacks is recreated from the source's catalog: identity kind, NOT NULL and
 * plain defaults survive; a sequence-backed default (which the copy cannot recreate) and a table
 * whose columns differ between the two sides are refused before anything is written.
 */

const scope: StoreCopyScope = { schemas: ["app"], ledgers: [{ schema: "app", name: "applied" }] };
const open: StorageKernel<unknown>[] = [];

afterEach(async () => {
  for (const kernel of open.splice(0)) await kernel.close();
});

async function pair(): Promise<{ source: StorageKernel<unknown>; target: StorageKernel<unknown> }> {
  const source = openPgliteKernel<unknown>({ PGlite });
  const target = openPgliteKernel<unknown>({ PGlite });
  open.push(source, target);
  for (const kernel of [source, target]) {
    await kernel.execute(sql`CREATE SCHEMA app`);
    await kernel.execute(sql`CREATE TABLE app.applied (id TEXT PRIMARY KEY, checksum TEXT)`);
    await kernel.execute(sql`INSERT INTO app.applied VALUES ('001', 'c1')`);
  }
  return { source, target };
}

/** A column's definition as the target's own catalog reports it. */
async function columnsOf(kernel: StorageKernel<unknown>, table: string) {
  return kernel.query(
    sql`SELECT column_name, is_nullable, column_default, is_identity, identity_generation
        FROM information_schema.columns WHERE table_schema = 'app' AND table_name = ${table} ORDER BY ordinal_position`
  );
}

it("recreates identity (ALWAYS and BY DEFAULT), NOT NULL and default columns on the target, and continues the counters", async () => {
  const { source, target } = await pair();
  await source.execute(sql`CREATE TABLE app.always_ids (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, label TEXT NOT NULL DEFAULT 'fresh')`);
  await source.execute(sql`CREATE TABLE app.default_ids (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n INTEGER)`);
  await source.execute(sql`INSERT INTO app.always_ids (label) VALUES ('one'), ('two')`);
  await source.execute(sql`INSERT INTO app.default_ids (n) VALUES (10)`);

  const report = await copyPgStore({ source, target, scope });

  expect(report).toEqual([
    { table: "app.always_ids", rows: 2, created: true },
    { table: "app.default_ids", rows: 1, created: true },
  ]);
  expect(await columnsOf(target, "always_ids")).toEqual([
    { column_name: "id", is_nullable: "NO", column_default: null, is_identity: "YES", identity_generation: "ALWAYS" },
    { column_name: "label", is_nullable: "NO", column_default: "'fresh'::text", is_identity: "NO", identity_generation: null },
  ]);
  expect(await columnsOf(target, "default_ids")).toEqual([
    { column_name: "id", is_nullable: "NO", column_default: null, is_identity: "YES", identity_generation: "BY DEFAULT" },
    { column_name: "n", is_nullable: "YES", column_default: null, is_identity: "NO", identity_generation: null },
  ]);
  expect(await target.query(sql`INSERT INTO app.always_ids DEFAULT VALUES RETURNING id, label`)).toEqual([{ id: 3, label: "fresh" }]);
  expect(await target.query(sql`INSERT INTO app.default_ids (n) VALUES (11) RETURNING id`)).toEqual([{ id: 2 }]);
});

it("refuses a created table whose default comes from a sequence, before writing anything", async () => {
  const { source, target } = await pair();
  await source.execute(sql`CREATE TABLE app.serials (id SERIAL PRIMARY KEY)`);
  await source.execute(sql`INSERT INTO app.serials DEFAULT VALUES`);

  const refusal = await copyPgStore({ source, target, scope }).then(() => null, (err: unknown) => err);
  expect(refusal).toBeInstanceOf(StoreCopyError);
  expect((refusal as Error).message).toBe(
    "column id takes its default from a sequence (nextval('app.serials_id_seq'::regclass)); this move cannot recreate it"
  );
  expect((await readCatalog({ kernel: target, scope })).map((table) => table.name)).toEqual(["applied"]);
});

it("refuses a table whose columns differ between source and target", async () => {
  const { source, target } = await pair();
  await source.execute(sql`CREATE TABLE app.notes (id TEXT PRIMARY KEY, body TEXT)`);
  await target.execute(sql`CREATE TABLE app.notes (id TEXT PRIMARY KEY, body INTEGER)`);

  await expect(copyPgStore({ source, target, scope })).rejects.toThrow(
    new StoreCopyError("table app.notes differs: source (id text, body text), target (id text, body integer)")
  );
});

it("readCatalog lists the scope's tables with their columns and primary keys", async () => {
  const { source } = await pair();
  await source.execute(sql`CREATE TABLE app.pairs (a TEXT NOT NULL, b INTEGER NOT NULL DEFAULT 1, PRIMARY KEY (a, b))`);
  expect(await readCatalog({ kernel: source, scope })).toEqual([
    {
      schema: "app",
      name: "applied",
      columns: [
        { name: "id", type: "text", notNull: true, expression: null, identity: "", generated: false },
        { name: "checksum", type: "text", notNull: false, expression: null, identity: "", generated: false },
      ],
      primaryKey: ["id"],
    },
    {
      schema: "app",
      name: "pairs",
      columns: [
        { name: "a", type: "text", notNull: true, expression: null, identity: "", generated: false },
        { name: "b", type: "integer", notNull: true, expression: "1", identity: "", generated: false },
      ],
      primaryKey: ["a", "b"],
    },
  ]);
});
