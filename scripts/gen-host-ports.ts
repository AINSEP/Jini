/** Generates HOST-PORTS.md: every exported `*Port`, `*Kit`, `*Deps` and registry function, with its
 * package and file:line. A second host reads it to learn what each Jini package asks the host to
 * bind (DESIGN §3, host checklist step 2).
 *   node --import tsx scripts/gen-host-ports.ts            write HOST-PORTS.md
 *   node --import tsx scripts/gen-host-ports.ts --check    exit 1 when HOST-PORTS.md is stale */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import ts from 'typescript';
import { isMainModule } from './lib/is-main-module.js';
import { packageSourceFiles, parseSource, sourcePackages } from './lib/package-sources.js';
import { REPO_ROOT } from './lib/walk-imports.js';

export interface HostPortEntry { pkg: string; name: string; category: 'port' | 'kit' | 'deps' | 'registry'; kind: string; file: string; line: number }

const REGISTRY_FUNCTION = /^(?:register|define|contribute|mount)[A-Z]/;

function categoryOf(required: { name: string; kind: string }): HostPortEntry['category'] | undefined {
  if (/Port$/.test(required.name)) return 'port';
  if (/Kit$/.test(required.name)) return 'kit';
  if (/Deps$/.test(required.name)) return 'deps';
  return required.kind === 'function' && REGISTRY_FUNCTION.test(required.name) ? 'registry' : undefined;
}

function declarationKind(node: ts.Statement): { name: string; kind: string } | undefined {
  if (ts.isInterfaceDeclaration(node)) return { name: node.name.text, kind: 'interface' };
  if (ts.isTypeAliasDeclaration(node)) return { name: node.name.text, kind: 'type' };
  if (ts.isFunctionDeclaration(node) && node.name) return { name: node.name.text, kind: 'function' };
  if (ts.isClassDeclaration(node) && node.name) return { name: node.name.text, kind: 'class' };
  return undefined;
}

function declaredNames(node: ts.Statement): { name: string; kind: string }[] {
  if (ts.isVariableStatement(node)) {
    return node.declarationList.declarations.flatMap(declaration => ts.isIdentifier(declaration.name) ? [{ name: declaration.name.text, kind: 'const' }] : []);
  }
  const declared = declarationKind(node);
  return declared ? [declared] : [];
}

const isExported = (node: ts.Statement): boolean => (ts.getCombinedModifierFlags(node as ts.Declaration) & ts.ModifierFlags.Export) !== 0;

function fileEntries(required: { pkg: string; filename: string; root: string }): HostPortEntry[] {
  const ast = parseSource({ file: required.filename, source: readFileSync(required.filename, 'utf8') });
  const file = relative(required.root, required.filename).split('\\').join('/');
  return ast.statements.filter(isExported).flatMap(node => declaredNames(node).flatMap(declared => {
    const category = categoryOf(declared);
    const line = ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1;
    return category ? [{ pkg: required.pkg, ...declared, category, file, line }] : [];
  }));
}

export function hostPortEntries(required: { root: string }, _optional: Record<string, never> = {}): HostPortEntry[] {
  const packages = sourcePackages({ packagesDir: join(required.root, 'packages') });
  const entries = packages.flatMap(pkg => packageSourceFiles({ directory: pkg.directory })
    .filter(filename => /\.tsx?$/.test(filename) && !filename.endsWith('.d.ts'))
    .flatMap(filename => fileEntries({ pkg: pkg.manifest.name, filename, root: required.root })));
  return entries.sort((a, b) => a.pkg.localeCompare(b.pkg) || a.file.localeCompare(b.file) || a.line - b.line);
}

export function renderHostPorts(required: { entries: readonly HostPortEntry[] }, _optional: Record<string, never> = {}): string {
  const lines = [
    '# Host ports', '',
    '<!-- Generated by scripts/gen-host-ports.ts; do not edit. -->', '',
    'Everything a Jini package asks its host to bind or register: `*Port`, `*Kit`, `*Deps`, and registry functions',
    '(`register*`, `define*`, `contribute*`, `mount*`). Bind each in your composition root with `satisfies <Port>`.', '',
  ];
  const byPackage = Map.groupBy(required.entries, entry => entry.pkg);
  for (const [pkg, entries] of byPackage) {
    lines.push(`## ${pkg}`, '', '| Name | Category | Kind | Where |', '|---|---|---|---|');
    for (const entry of entries) lines.push(`| \`${entry.name}\` | ${entry.category} | ${entry.kind} | \`${entry.file}:${entry.line}\` |`);
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

export function main(argv: readonly string[], required: { root: string } = { root: REPO_ROOT }): number {
  const text = renderHostPorts({ entries: hostPortEntries(required) });
  const path = join(required.root, 'HOST-PORTS.md');
  if (argv.includes('--check')) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (current !== text) console.error('HOST-PORTS.md is stale: run node --import tsx scripts/gen-host-ports.ts');
    return current === text ? 0 : 1;
  }
  writeFileSync(path, text);
  return 0;
}

if (isMainModule({ moduleUrl: import.meta.url, entryPath: process.argv[1] })) process.exitCode = main(process.argv.slice(2));
